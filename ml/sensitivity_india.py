"""How far does the India 3.5x move with homes per transformer?

The India headline (FINDINGS.md finding 10) is 35 vehicles charging on arrival
against 123 coordinated on a 100 kVA unit, a 3.5x gain, at **150 homes per
transformer**. That count is an estimate from typical Indian sizing practice
(70-80 kW on a 100 kVA unit at 60-75% loading), not a measurement, and the first
guess of 40 homes was wrong in a way that changed the answer. This sweeps it.

    python sensitivity_india.py

Rows: 100 / 150 / 200 homes (150 is the base). GUESS: the plausible range for a
100 kVA residential unit; no open source publishes consumers per transformer.
Everything else is held at the published settings, and the fleet is the
deterministic FADA-weighted mix, so there is no seed noise to band.

This is sensitivity to an assumption, not validation: the baseline shape is
Grid-India *system* demand, not a metered feeder, and the fleet is assumed.

Writes artifacts/sensitivity_india.json.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "src"))
sys.path.insert(0, str(HERE.parent / "backend"))

from app.optimizer import naive_schedule, optimize_schedule  # noqa: E402
from export_india_capacity import HOMES, residential_baseline  # noqa: E402
from india_fleet import SEGMENTS, dt_ratings_kw, DT_RATINGS_KVA, indian_fleet  # noqa: E402
from india_load import hourly_shape, load as load_demand  # noqa: E402

OUT = HERE / "artifacts" / "sensitivity_india.json"
HEADLINE_KVA = 100
HOME_COUNTS = [100, 150, 200]
CARBON = [250.0] * 24  # flat: this is power against a rating, not carbon


def dumb_capacity(rating: float, base: list[float]) -> int:
    best = 0
    for n in range(1, 4001):
        if max(naive_schedule(indian_fleet(n))[h] + base[h] for h in range(24)) <= rating:
            best = n
        else:
            return best
    raise RuntimeError(f"dumb sweep hit its 4000 bound at {rating:.0f} kW")


def coordinated_capacity(rating: float, base: list[float]) -> int:
    headroom = sum(max(rating - b, 0.0) for b in base)
    mean_need = sum(SEGMENTS[s]["energy_kwh"] * w
                    for s, w in (("e2w", .564), ("e3w", .351), ("ecar", .078)))
    bound = int(1.6 * headroom / mean_need) + 50
    lo, hi = 0, bound
    while lo < hi:
        mid = (lo + hi + 1) // 2
        try:
            optimize_schedule(indian_fleet(mid), CARBON, residential_baseline_kw=base,
                              feeder_capacity_kw=rating)
            lo = mid
        except ValueError:
            hi = mid - 1
    if lo >= bound:
        raise RuntimeError(f"bisection bound {bound} reached at {rating:.0f} kW")
    return lo


def main() -> None:
    shape = hourly_shape(load_demand())
    kw = dict(zip(DT_RATINGS_KVA, dt_ratings_kw()))[HEADLINE_KVA]
    rows = []
    print(f"{HEADLINE_KVA} kVA = {kw:.1f} kW; base homes {HOMES}\n")
    print(f"{'homes':>6} {'res peak':>9} {'dumb':>6} {'coord':>6} {'gain':>6}")
    print("-" * 38)
    for homes in HOME_COUNTS:
        base = residential_baseline(homes, shape)
        peak = max(base)
        if peak >= kw:
            rows.append({"homes": homes, "residential_peak_kw": round(peak, 1), "overloaded": True})
            print(f"{homes:>6} {peak:>9.1f}   houses alone exceed the rating")
            continue
        d, c = dumb_capacity(kw, base), coordinated_capacity(kw, base)
        rows.append({"homes": homes, "residential_peak_kw": round(peak, 1), "dumb": d,
                     "coordinated": c, "gain": round(c / max(d, 1), 2), "overloaded": False})
        print(f"{homes:>6} {peak:>9.1f} {d:>6} {c:>6} {c / max(d, 1):>5.2f}x", flush=True)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "note": "Generated by ml/sensitivity_india.py - sensitivity to assumptions, not validation.",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "rating_kva": HEADLINE_KVA,
        "rating_kw": round(kw, 1),
        "base_homes": HOMES,
        "rows": rows,
    }, indent=2), encoding="utf-8")
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
