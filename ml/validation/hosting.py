"""Hosting capacity on a real street's demand, against the modelled baseline's answer.

Re-runs the 250 kW headline (finding 1) with exactly the method and fleet of `sensitivity_hosting.py`
(realistic fleet, seed 0, 12 sampled nights, charge-on-arrival found on a step-1 grid, coordinated found
by bisecting the LP), changing one thing: the residential baseline is a real street of 200 homes drawn
from a public smart-meter panel (`baselines.py`) instead of scaled system load.

Per region, three streets (p10, median, p90 by evening peak per home) in two forms: the annual-average
day and the winter-average day, which is the binding season for an evening peak. Rows are saved as they
finish, so an interrupted run resumes.

    python hosting.py uk
    python hosting.py spain
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

import sensitivity_hosting as sh  # noqa: E402

ART = HERE.parent / "artifacts"


def main() -> None:
    region = sys.argv[1] if len(sys.argv) > 1 else ""
    src = ART / f"validation_baselines_{region}.json"
    if not src.exists():
        sys.exit(f"run baselines.py {region} first")
    base = json.loads(src.read_text(encoding="utf-8"))
    out_path = ART / f"validation_hosting_{region}.json"
    done = json.loads(out_path.read_text(encoding="utf-8")) if out_path.exists() else {"rows": {}}
    for label in ("median", "p10", "p90"):
        for form in ("winter", "annual"):
            key = f"{label}_{form}"
            if key in done["rows"]:
                print(f"  {key}: saved, skipping", flush=True)
                continue
            street = base["streets"][label][form]
            sh.ROWS[key] = ("real", f"{base['name']} street, {label} evening peak, {form}",
                            {"baseline_kw": street["profile_kw"]})
            r = sh.run_row(key)
            r.update(street_peak_kw_per_home=street["peak_kw_per_home"], street_peak_hour=street["peak_hour"],
                     street_peak_to_trough=street["peak_to_trough"], street=label, form=form)
            done["rows"][key] = r
            out_path.write_text(json.dumps(done, indent=1), encoding="utf-8")
            print(f"  {key}: peak {r['street_peak_kw_per_home']} kW/home at {r['street_peak_hour']}h -> "
                  f"dumb {r['dumb']}/{r['dumb_fine']} coordinated {r['coordinated']} = {r['gain']}x "
                  f"({r['gain_fine']}x fine) [{r['seconds']}s]", flush=True)
    done["note"] = "Generated by ml/validation/hosting.py"
    out_path.write_text(json.dumps(done, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
