"""India: a published-figure check, because no open household smart-meter data exists to validate against.

Prayas Energy Group's eMARC project meters 115 households (Pune City, semi-urban and rural Pune,
Aurangabad, Kanpur Rural, Gonda) at one-minute resolution. The raw data is not public; Prayas publishes
dashboards and summary text. The one quantitative figure on its load-pattern page that bears on a
transformer is the evening peak for Pune City: around 9 pm, 200 to 250 W per household in non-summer
months.
(https://energy.prayaspune.org/our-work/article-and-blog/electricity-load-patterns)

The Indian hosting-capacity model (finding 10) calibrates its baseline to Delhi's average electrified
household, about 260 kWh a month, which gives a 0.384 kW per-home evening peak. This re-runs the
100 kVA search with the baseline scaled to the published Pune peak, as a bound on how much the model's
level matters. It is *not* validation against raw data, and says so: a published summary figure from
one city is much weaker evidence than a meter panel, and Pune is not Delhi.

    python india.py       # -> artifacts/validation_india.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

import export_india_capacity as ic  # noqa: E402

OUT = HERE.parent / "artifacts" / "validation_india.json"
RATING_KVA = 100
PUBLISHED_W = {"low": 200, "mid": 225, "high": 250}      # Pune City, 9 pm, non-summer
CARBON = [250.0] * 24                                    # flat: this is power against a rating


def capacities(base: list[float], rating_kw: float) -> tuple[int, int]:
    dumb = 0
    for n in range(1, 4001):
        if max(ic.naive_schedule(ic.indian_fleet(n))[h] + base[h] for h in range(24)) <= rating_kw:
            dumb = n
        else:
            break
    headroom = sum(max(rating_kw - b, 0.0) for b in base)
    mean_need = sum(ic.SEGMENTS[s]["energy_kwh"] * w for s, w in (("e2w", .564), ("e3w", .351), ("ecar", .078)))
    lo, hi = 0, int(1.6 * headroom / mean_need) + 50
    while lo < hi:
        mid = (lo + hi + 1) // 2
        try:
            ic.optimize_schedule(ic.indian_fleet(mid), CARBON, residential_baseline_kw=base, feeder_capacity_kw=rating_kw)
            lo = mid
        except ValueError:
            hi = mid - 1
    return dumb, lo


def main() -> None:
    demand = ic.load_demand()
    shape = ic.hourly_shape(demand)
    kw = ic.dt_ratings_kw()[ic.DT_RATINGS_KVA.index(RATING_KVA)]
    model = ic.residential_baseline(ic.HOMES, shape)
    rows = []

    def add(label: str, base: list[float], note: str) -> None:
        d, c = capacities(base, kw)
        rows.append({"label": label, "note": note, "peak_kw_per_home": round(max(base) / ic.HOMES, 3),
                     "peak_hour": int(max(range(24), key=lambda h: base[h])),
                     "dumb": d, "coordinated": c, "gain": round(c / max(d, 1), 2)})
        print(f"  {label:<34} peak {rows[-1]['peak_kw_per_home']} kW/home -> {d} -> {c} = {rows[-1]['gain']}x", flush=True)

    add("Model (Delhi consumption)", model, "the baseline finding 10 uses")
    for tag, w in PUBLISHED_W.items():
        scale = (w / 1000 * ic.HOMES) / max(model)
        add(f"Scaled to Pune published {w} W", [round(v * scale, 3) for v in model],
            "model shape, peak set to the published figure")
    out = {
        "note": "Generated by ml/validation/india.py - a published-figure check, not validation on raw data.",
        "rating_kva": RATING_KVA, "homes": ic.HOMES,
        "published": {"source": "Prayas Energy Group, eMARC, Pune City evening peak, non-summer",
                      "url": "https://energy.prayaspune.org/our-work/article-and-blog/electricity-load-patterns",
                      "peak_hour": 21, "peak_w_per_home": [200, 250], "households_metered": 115},
        "rows": rows,
    }
    OUT.write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
