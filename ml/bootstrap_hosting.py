"""Bootstrap confidence interval on the headline hosting-capacity gain (finding 1).

finding 1 reports a median gain of 4.1x over 20 fleet draws at 250 kW, range 3.3-5.3x.
A range over 20 draws is not a confidence interval. This resamples those 20 draws (with
replacement, 10,000 resamples) to put a formal 95% CI on the median gain, using the exact
per-draw dumb/coordinated counts already recorded in artifacts/hosting_seeds.json by
export_hosting_capacity.py -- no new LP solves, since the raw draws already exist.

    python bootstrap_hosting.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
SEEDS = json.load(open(HERE / "artifacts" / "hosting_seeds.json", encoding="utf-8"))

OUTS = [HERE / "artifacts" / "hosting_bootstrap.json",
        HERE.parent / "frontend" / "src" / "data" / "hosting_bootstrap.json",
        HERE.parent / "backend" / "app" / "data" / "hosting_bootstrap.json"]

N_BOOT = 10_000
RNG = np.random.default_rng(0)


def gains_for_rating(rating_kw: int) -> np.ndarray:
    prefix = f"{rating_kw}:"
    draws = [v for k, v in SEEDS.items() if k.startswith(prefix)]
    return np.array([d["coordinated"] / d["dumb"] for d in draws])


def bootstrap_median_ci(x: np.ndarray, n_boot: int = N_BOOT, alpha: float = 0.05) -> tuple[float, float, float]:
    n = len(x)
    boot_medians = np.empty(n_boot)
    for i in range(n_boot):
        resample = RNG.choice(x, size=n, replace=True)
        boot_medians[i] = np.median(resample)
    lo, hi = np.percentile(boot_medians, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return float(np.median(x)), float(lo), float(hi)


def main() -> None:
    from datetime import datetime, timezone

    ratings = {}
    for rating in (160, 250, 400, 630):
        x = gains_for_rating(rating)
        median, lo, hi = bootstrap_median_ci(x)
        ratings[str(rating)] = {
            "n_draws": len(x),
            "median_gain": round(median, 3),
            "ci95_lo": round(lo, 3),
            "ci95_hi": round(hi, 3),
            "raw_gains": [round(v, 4) for v in sorted(x)],
        }
        print(f"{rating} kW: n={len(x)} median={median:.2f}x  95% CI [{lo:.2f}x, {hi:.2f}x]")

    out = {
        "note": "Generated by ml/bootstrap_hosting.py - percentile bootstrap (10,000 resamples) on finding 1's "
                "fleet-draw gains, from the raw per-draw counts in hosting_seeds.json. No new LP solves.",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "n_boot": N_BOOT,
        "method": "percentile bootstrap of the median gain (coordinated/dumb per draw), resampled with replacement",
        "ratings": ratings,
    }
    text = json.dumps(out, indent=1)
    for p in OUTS:
        p.write_text(text, encoding="utf-8")
    print("wrote", OUTS[0])


if __name__ == "__main__":
    main()
