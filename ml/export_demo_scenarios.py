"""Store one real simulator result per grid era, for the page to show while the API wakes.

The API is a serverless function. After a quiet spell its first request takes seconds, and
a visitor who lands on the Simulator during that wait would otherwise see an error and an
empty form, which is the worst possible first screen. This runs the real solver once per era
on the default night and default settings and saves the response, so the page can open on a
true result, clearly labelled as stored, and replace it the moment the live API answers.

    python export_demo_scenarios.py        # -> frontend/src/data/demo_scenarios.json

Re-run it whenever the served nights or the optimizer change.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "backend"))

from fastapi.testclient import TestClient  # noqa: E402

from app import data_sources  # noqa: E402
from app.main import app  # noqa: E402

OUT = HERE.parent / "frontend" / "src" / "data" / "demo_scenarios.json"

#: The Simulator's defaults, as App.tsx sends them.
DEFAULTS = {"ev_count": 80, "charger_kw": 7.0, "arrival_hour": 18, "deadline_hour": 7,
            "energy_per_vehicle_kwh": 9.2, "objective": "emissions", "region": "ES"}


def main() -> None:
    client = TestClient(app)
    out: dict = {"note": "Generated by ml/export_demo_scenarios.py - a real solver result, stored. Do not edit by hand.",
                 "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "eras": {}}
    for era in data_sources.eras():
        day = data_sources.default_day(era)
        r = client.post("/api/scenario", json={**DEFAULTS, "era": era, "day": day})
        r.raise_for_status()
        body = r.json()
        body["run_id"] = None
        out["eras"][era] = {"days": data_sources.available_days(era), "default_day": day,
                            "year_stats": data_sources.year_stats(era), "response": body}
        print(f"{era}: {day} -> CO2 {body['emissions_reduction_pct']}%, cost {body['cost_reduction_pct']}%, peak {body['peak_reduction_pct']}%")
    OUT.write_text(json.dumps(out, separators=(",", ":")), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
