"""How fine-grained a margin search still fails to hit the 5% overload target (finding 23 follow-up).

Finding 23 swept 6 discrete margins (0/5/10/15/20/30%) and reported the best observed outcome: 35%
overload at m=20%, sigma=3% (the one measured error level -- the national day-ahead demand
forecaster's own error, `train_india.py`, MAPE 2.4-2.5%). A 6-point grid cannot rule out that a
margin *between* grid points reaches the 5% target, and 60 draws per cell gives no formal
uncertainty bound on "35%". This closes both gaps for the one real error level:

  1. A margin grid every 4 points from 0% to 40% (11 points, not 6).
  2. 100 draws per margin instead of 60, for a tighter estimate.
  3. A bootstrap 95% CI on the overload probability at the best margin found, and on the minimum
     achievable overload probability over the whole grid.

Only sigma=3% is re-run here -- it is the one row in finding 23 backed by a real measured error
figure; the 5/10/20% rows are guessed brackets and a finer grid on a guess would not be a stronger
claim, just a more precise one about an assumption.

    python india_margin_search.py        # -> artifacts/india_margin_search.json, frontend and backend copies
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))

import export_india_capacity as ic  # noqa: E402
from india_robustness import RATING_KVA, RHO, noise  # noqa: E402

OUTS = [HERE / "artifacts" / "india_margin_search.json",
        HERE.parent / "frontend" / "src" / "data" / "india_margin_search.json",
        HERE.parent / "backend" / "app" / "data" / "india_margin_search.json"]
SIGMA = 0.03
MARGINS = [round(m, 2) for m in np.arange(0.0, 0.41, 0.04)]
DRAWS = 100
TARGET = 0.05
CARBON = [250.0] * 24
N_BOOT = 10_000


def coordinated_capacity(base: list[float], cap_kw: float) -> int:
    headroom = sum(max(cap_kw - b, 0.0) for b in base)
    mean_need = sum(ic.SEGMENTS[s]["energy_kwh"] * w for s, w in (("e2w", .564), ("e3w", .351), ("ecar", .078)))
    lo, hi = 0, int(1.6 * headroom / mean_need) + 50
    while lo < hi:
        mid = (lo + hi + 1) // 2
        try:
            ic.optimize_schedule(ic.indian_fleet(mid), CARBON, residential_baseline_kw=base, feeder_capacity_kw=cap_kw)
            lo = mid
        except ValueError:
            hi = mid - 1
    return lo


def overload_draws(n: int, base: list[float], cap_kw: float, rating_kw: float, seed: int) -> np.ndarray:
    """Per-draw overload indicator (1 = overloaded), length DRAWS."""
    rng = np.random.default_rng(seed)
    fleet = ic.indian_fleet(n)
    out = np.zeros(DRAWS, dtype=int)
    for i in range(DRAWS):
        e = noise(SIGMA, rng)
        forecast = [b * (1 + x) for b, x in zip(base, e)]
        try:
            sched = ic.optimize_schedule(fleet, CARBON, residential_baseline_kw=forecast, feeder_capacity_kw=cap_kw)
        except ValueError:
            out[i] = 1
            continue
        load = [sched[h] for h in range(24)]
        if max(load[h] + base[h] for h in range(24)) > rating_kw + 1e-6:
            out[i] = 1
    return out


def bootstrap_ci(draws: np.ndarray, n_boot: int = N_BOOT, alpha: float = 0.05, rng: np.random.Generator | None = None) -> tuple[float, float]:
    rng = rng or np.random.default_rng(1)
    n = len(draws)
    boot = np.empty(n_boot)
    for i in range(n_boot):
        boot[i] = rng.choice(draws, size=n, replace=True).mean()
    lo, hi = np.percentile(boot, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return float(lo), float(hi)


def main() -> None:
    demand = ic.load_demand()
    base = ic.residential_baseline(ic.HOMES, ic.hourly_shape(demand))
    rating = ic.dt_ratings_kw()[ic.DT_RATINGS_KVA.index(RATING_KVA)]

    rows = []
    for m in MARGINS:
        cap_kw = rating * (1 - m)
        n = coordinated_capacity(base, cap_kw)
        draws = overload_draws(n, base, cap_kw, rating, seed=int(m * 1000) + 7)
        prob = float(draws.mean())
        lo, hi = bootstrap_ci(draws)
        rows.append({
            "margin_pct": round(m * 100, 1),
            "capacity": n,
            "overload_prob": round(prob, 4),
            "ci95_lo": round(lo, 4),
            "ci95_hi": round(hi, 4),
        })
        print(f"margin {m*100:5.1f}%: capacity {n:4d}  overload {prob:.3f}  95% CI [{lo:.3f}, {hi:.3f}]", flush=True)

    best = min(rows, key=lambda r: r["overload_prob"])
    meets_target = [r for r in rows if r["ci95_hi"] <= TARGET]

    out = {
        "note": "Generated by ml/india_margin_search.py - a finer-grained, CI-backed follow-up to finding 23 at the one measured error level (3%).",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "rating_kva": RATING_KVA,
        "homes": ic.HOMES,
        "error_sd_pct": SIGMA * 100,
        "error_correlation": RHO,
        "draws_per_margin": DRAWS,
        "margin_grid_step_pct": 4,
        "target_overload_prob": TARGET,
        "rows": rows,
        "best_margin_pct": best["margin_pct"],
        "best_overload_prob": best["overload_prob"],
        "best_overload_ci95": [best["ci95_lo"], best["ci95_hi"]],
        "any_margin_meets_target_at_95ci": len(meets_target) > 0,
        "caveats": [
            "Only sigma=3% (the measured national day-ahead demand error) is covered here; finding 23's "
            "5/10/20% rows are unmeasured brackets and are not re-run at this resolution.",
            "100 draws per margin point, bootstrap 95% CI (10,000 resamples) on the overload probability "
            "at each margin.",
            "One night shape (the annual mean); no seasonal variation, as in finding 23.",
        ],
    }
    text = json.dumps(out, indent=1)
    for p in OUTS:
        p.write_text(text, encoding="utf-8")
    print("\nbest margin:", best)
    print("any margin meets 5% target at 95% CI upper bound:", len(meets_target) > 0)
    print("wrote", OUTS[0])


if __name__ == "__main__":
    main()
