"""Would more training data make the Spanish day-ahead forecaster better?

The deployed ridge model trains on three years (2015-2017) and is scored on
2018. Before spending effort on a bigger dataset it is worth knowing whether the
model is data-starved at all, so this holds the test year fixed and trains on
1, 2 and 3 years, and reports error and decision regret (share of the
achievable saving captured, finding 3).

    python learning_curve.py

If error keeps falling as years are added, more data is the lever. If it is
flat, the limit is the features or the grid's own unpredictability, and
collecting more of the same would not help.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "src"))
sys.path.insert(0, str(HERE.parent / "backend"))

from spread_gate import evaluate, night_curves, sweep  # noqa: E402
from train_v2 import TRAIN_END, build  # noqa: E402

OUT = HERE / "artifacts" / "learning_curve.json"
SPLITS = {
    "2017 only (1 yr)": "2017-01-01",
    "2016-2017 (2 yr)": "2016-01-01",
    "2015-2017 (3 yr)": "2015-01-01",
}


def main() -> None:
    data, feats = build(with_weather=False)
    test = data.loc[TRAIN_END:].iloc[1:]
    rows = []
    print(f"{'training span':<20} {'rows':>7} {'MAE':>7} {'captured':>9}")
    for label, start in SPLITS.items():
        train = data.loc[f"{start} 00:00:00+00:00":TRAIN_END]
        m = Ridge(alpha=1.0).fit(train[feats], train["ci"])
        pred = pd.Series(m.predict(test[feats]), index=test.index)
        mae = float(np.abs(pred - test["ci"]).mean())
        rows_n = evaluate(night_curves(test["ci"], pred, "Europe/Madrid"))
        cap = sweep(rows_n, "pred_saving", [-1e9])[0]["captured_of_oracle_pct"]
        rows.append({"training": label, "rows": len(train), "mae": round(mae, 3), "captured_pct": cap})
        print(f"{label:<20} {len(train):>7,} {mae:>7.2f} {cap:>8}%")
    OUT.write_text(json.dumps({"note": "Generated by ml/learning_curve.py", "test": "2018", "rows": rows},
                              indent=2), encoding="utf-8")
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
