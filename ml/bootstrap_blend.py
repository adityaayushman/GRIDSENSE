"""Is the blend's edge over the deployed ridge more than night-to-night noise?

Paired bootstrap over nights: resample nights with replacement, recompute each model's captured share
of the achievable saving on the same resample, and look at the difference. A gap whose interval spans zero
is not an improvement.

    python bootstrap_blend.py        # -> artifacts/bootstrap_blend.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "src"))
sys.path.insert(0, str(HERE.parent / "backend"))

import pandas as pd  # noqa: E402

from spread_gate import evaluate, night_curves  # noqa: E402
from train_decision_aware import Blend, PerHour, Plain, build, gbm, ridge  # noqa: E402
from train_modern import year_span  # noqa: E402

OUT = HERE / "artifacts" / "bootstrap_blend.json"
B = 2000
FOLDS = {
    "2018 (train 2015-17)": ((2015, 2017), 2018),
    "2025 (train 2024)": ((2024, 2024), 2025),
    "2025 (train 2022-24)": ((2022, 2024), 2025),
}


def nights(model, cols, tr, te):
    keep = cols + ["lhour"]
    model.fit(tr[keep], tr["ci"])
    pred = pd.Series(model.predict(te[keep]), index=te.index)
    ev = evaluate(night_curves(te["ci"], pred, "Europe/Madrid"))
    return {r["night"]: r for r in ev}


def captured(rows: list[dict]) -> float:
    gain = sum(r["e_naive"] - r["e_fc"] for r in rows)
    oracle = sum(r["e_naive"] - r["e_or"] for r in rows)
    return gain / oracle * 100


def main() -> None:
    f, cols, cols_resid = build()
    rng = np.random.default_rng(11)
    out: dict = {"note": "Generated by ml/bootstrap_blend.py", "resamples": B, "folds": {}}
    for name, ((a, b), y) in FOLDS.items():
        tr, te = year_span(f, a, b), year_span(f, y, y)
        base = nights(Plain(ridge), cols, tr, te)
        blend = nights(Blend(PerHour(ridge), Plain(gbm)), cols_resid, tr, te)
        keys = sorted(set(base) & set(blend))
        rb, rl = [base[k] for k in keys], [blend[k] for k in keys]
        diffs = []
        for _ in range(B):
            i = rng.integers(0, len(keys), len(keys))
            diffs.append(captured([rl[j] for j in i]) - captured([rb[j] for j in i]))
        lo, hi = np.percentile(diffs, [2.5, 97.5])
        out["folds"][name] = {
            "nights": len(keys), "ridge_pct": round(captured(rb), 1), "blend_pct": round(captured(rl), 1),
            "diff_pp": round(captured(rl) - captured(rb), 1), "ci95_pp": [round(float(lo), 1), round(float(hi), 1)],
        }
        r = out["folds"][name]
        print(f"{name:<24} ridge {r['ridge_pct']}%  blend {r['blend_pct']}%  diff {r['diff_pp']:+}pp  95% [{r['ci95_pp'][0]:+}, {r['ci95_pp'][1]:+}]",
              flush=True)
    OUT.write_text(json.dumps(out, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
